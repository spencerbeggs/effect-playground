import { Schema } from "effect";

/**
 * A User entity representing a person in the system.
 *
 * Built with `Schema.Class` which provides:
 * - Runtime validation via `Schema.decodeUnknown(User)`
 * - Type-safe constructor via `new User({ id, name })` — construction itself
 *   validates, so an out-of-domain field throws a `SchemaError`
 * - Structural equality (v4 makes `Equal.equals` structural by default)
 *
 * Note this is `Schema.Class`, not `Schema.TaggedClass` — there is no `_tag`
 * field on a `User`. Reach for `TaggedClass` when you need one for
 * discriminated-union matching.
 *
 * @example
 * ```ts
 * // Create a user
 * const user = new User({ id: 1, name: "Alice" });
 *
 * // Validate unknown data
 * const parsed = Schema.decodeUnknownSync(User)({ id: 1, name: "Alice" });
 *
 * // Encode to plain object
 * const plain = Schema.encodeSync(User)(user);
 * ```
 *
 * @public
 */
export class User extends Schema.Class<User>("User")({
	/**
	 * Unique identifier for the user (auto-generated by UserService).
	 *
	 * `Schema.Int` rather than `Schema.Number`: the plain number schema also
	 * admits `NaN` and `±Infinity`, which are not valid IDs.
	 */
	id: Schema.Int,
	/** Display name of the user */
	name: Schema.String,
}) {}
